"""The deblob verification: for every stock vendor .ko, does the VXTux
build produce a module with the same name, and does it export the same
API?

Three levels of evidence, reported separately so a partial result is
never dressed up as a full one:

  LEVEL 1  NAME   the build emits a .ko with the stock file name
  LEVEL 2  API    that .ko exports every symbol the stock .ko exported
  LEVEL 3  DEPS   that .ko does not import anything the stock one did
                  not (new imports are listed, not hidden)

Usage:
    python3 verify_deblob.py
"""
import os
import re
import subprocess
import sys

NM = (r"C:\Users\Administrator\scoop\apps\gcc-aarch64-none-linux-gnu"
      r"\15.2.rel1\bin\aarch64-none-linux-gnu-nm.exe")
STOCK_DIR = "E:/vxtux_build_repo/donors/stock_vendor_modules"
BUILT_KO = "E:/vxtux_build_repo/built_kos"
STOCK_LIST = "E:/vxtux_build_repo/donors/stock_modules.txt"
REPORT = "E:/vxtux_build_repo/docs/DEBLOB_VERIFICATION.md"

ARTEFACT_PREFIX = (
    "__cfi_", "__crc_", "__mod_of__", "__typeid__", "__pfx_",
    "__initcall_", "__exitcall_", "__ksymtab", "__kcrctab", "__kstrtab",
    "__modver", "__this_module", "__param", "__bug_table", "__jump_table",
    "__used", "__UNIQUE_ID", "_note_", "__gnu_local", "__stack_chk",
    "__stack_chk_fail", "__memcpy", "__aeabi_", "__exidx", "__init_",
    "__bss_start", "__bss_stop", "__data_start", "__end_", "_GLOBAL_",
    "__init_array", "__fini_array", "__dso_handle", "__TMC_END__",
    "__FRAME_END__", "__bss_start__", "__bss_end__", "__per_cpu_start",
)
ARTEFACT_EXACT = {
    "__this_module", "__modver", "_etext", "_edata", "_end",
    "__init_array_start", "__init_array_end",
    "__fini_array_start", "__fini_array_end",
}


def is_artefact(s):
    return s in ARTEFACT_EXACT or s.startswith(ARTEFACT_PREFIX)


def nm(path):
    r = subprocess.run([NM, path], capture_output=True, text=True,
                       timeout=300)
    if r.returncode != 0:
        return None, None
    ex, im = set(), set()
    for line in r.stdout.splitlines():
        p = line.split()
        if len(p) < 2:
            continue
        typ = p[-2] if len(p) >= 3 else p[0]
        name = p[-1]
        if typ == "U":
            im.add(name)
        elif typ.isalpha() and typ.isupper():
            ex.add(name)
    return ex, im


def main():
    stock = []
    with open(STOCK_LIST, encoding="utf-8", errors="replace") as f:
        for line in f:
            s = re.split(r"[\t|,;]", line.strip())[0].strip()
            if s:
                stock.append(s)

    built = {}
    if os.path.isdir(BUILT_KO):
        for root, _, fs in os.walk(BUILT_KO):
            for fn in fs:
                if fn.endswith(".ko"):
                    built.setdefault(fn[:-3], os.path.join(root, fn))

    lines = []
    lines.append("# Deblob verification")
    lines.append("")
    lines.append("Generated by `donors/verify_deblob.py`.")
    lines.append("")
    lines.append("The stock ROM ships 31 vendor .ko in /lib/modules. For the")
    lines.append("deblob to be real, the VXTux build must produce a module")
    lines.append("with the SAME FILE NAME, exporting the SAME API, so the")
    lines.append("loader can insmod it and nothing that bound to the stock")
    lines.append("blob breaks.")
    lines.append("")
    lines.append("| # | stock .ko | name | API | new imports |")
    lines.append("|---|-----------|------|-----|-------------|")

    name_ok, api_ok, api_gap = [], [], []
    rows = []
    for i, s in enumerate(stock, 1):
        sp = os.path.join(STOCK_DIR, s + ".ko")
        bp = built.get(s)
        if not os.path.exists(sp):
            rows.append((i, s, "-", "-", "-", "no stock blob"))
            continue
        if not bp:
            rows.append((i, s, "MISSING", "-", "-",
                         "the build emits no module with this name"))
            continue
        se, si = nm(sp)
        be, bi = nm(bp)
        if se is None or be is None:
            rows.append((i, s, "OK", "nm error", "-", ""))
            continue
        s_api = {x for x in se if not is_artefact(x)}
        b_api = {x for x in be if not is_artefact(x)}
        missing = sorted(s_api - b_api)
        newimp = sorted(bi - si)
        name_ok.append(s)
        if missing:
            api_gap.append((s, missing))
            rows.append((i, s, "OK", f"**{len(missing)} missing**",
                         len(newimp), ", ".join(missing[:6])))
        else:
            api_ok.append(s)
            rows.append((i, s, "OK", "identical", len(newimp), ""))

    for r in rows:
        lines.append(f"| {r[0]} | `{r[1]}` | {r[2]} | {r[3]} | {r[4]} |")

    n = len(stock)
    lines.append("")
    lines.append("## Result")
    lines.append("")
    lines.append(f"- stock vendor blobs: **{n}**")
    lines.append(f"- a .ko with the same name is built: **{len(name_ok)}**"
                 f" ({100.0 * len(name_ok) / n:.1f}%)")
    lines.append(f"- and its API is identical to the stock blob's: "
                 f"**{len(api_ok)}** ({100.0 * len(api_ok) / n:.1f}%)")
    if api_gap:
        lines.append(f"- API gaps: **{len(api_gap)}**")
        lines.append("")
        for s, m in api_gap:
            lines.append(f"  - `{s}`: {m}")
    lines.append("")
    lines.append("### The ones with no module yet")
    lines.append("")
    for i, s, nstat, a, ni, note in rows:
        if nstat == "MISSING":
            lines.append(f"- `{s}` - {note}")
    lines.append("")
    lines.append("`new imports` counts symbols the replacement needs that the")
    lines.append("stock blob did not. A port may legitimately use a different")
    lines.append("kernel API, so these are listed, not counted as a failure.")
    lines.append("")

    os.makedirs(os.path.dirname(REPORT), exist_ok=True)
    with open(REPORT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))

    print("\n".join(lines[-40:]))
    print()
    print(f"written: {REPORT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
